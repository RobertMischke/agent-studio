#!/usr/bin/env node
/**
 * Build a coverage-map markdown table that lists every Playwright spec
 * grouped by its e2e/<folder>/ location, with the first describe-or-test
 * title as the one-line summary. The result is meant to live inside
 * `e2e/README.md` between the COVERAGE-MAP-START and COVERAGE-MAP-END
 * markers; re-running this script refreshes it idempotently.
 *
 *   node scripts/generate-e2e-coverage-map.mjs            # print only
 *   node scripts/generate-e2e-coverage-map.mjs --write    # rewrite README block
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, basename } from 'node:path';

const ROOT = 'e2e';
const README = join(ROOT, 'README.md');

function listFolders() {
  return readdirSync(ROOT, { withFileTypes: true })
    .filter(d => d.isDirectory() && !d.name.startsWith('_') && d.name !== 'helpers' && d.name !== 'fixtures')
    .map(d => d.name)
    .sort();
}

function listSpecs(folder) {
  const dir = join(ROOT, folder);
  return readdirSync(dir)
    .filter(f => f.endsWith('.spec.ts'))
    .sort();
}

/** Extract a one-line summary: first `describe('x', …)`, falling back
 *  to first `test('x', …)`. */
function summarise(path) {
  const text = readFileSync(path, 'utf8');
  let m = /describe\(\s*(['"`])([^'"`]+)\1/.exec(text);
  if (m) return m[2];
  m = /\btest\(\s*(['"`])([^'"`]+)\1/.exec(text);
  if (m) return m[2];
  return '(no description)';
}

function buildBlock() {
  const folders = listFolders();
  const lines = ['<!-- COVERAGE-MAP-START — regenerated by scripts/generate-e2e-coverage-map.mjs -->', ''];
  for (const folder of folders) {
    const specs = listSpecs(folder);
    if (specs.length === 0) continue;
    lines.push(`### \`${folder}/\` — ${specs.length} spec${specs.length === 1 ? '' : 's'}`);
    lines.push('');
    lines.push('| Spec | Summary |');
    lines.push('|------|---------|');
    for (const f of specs) {
      const summary = summarise(join(ROOT, folder, f)).replace(/\|/g, '\\|');
      lines.push(`| \`${f}\` | ${summary} |`);
    }
    lines.push('');
  }
  lines.push('<!-- COVERAGE-MAP-END -->');
  return lines.join('\n');
}

const block = buildBlock();
const write = process.argv.includes('--write');

if (!write) {
  console.log(block);
  process.exit(0);
}

const readme = readFileSync(README, 'utf8');
const startMark = '<!-- COVERAGE-MAP-START';
const endMark = 'COVERAGE-MAP-END -->';
const startIdx = readme.indexOf(startMark);
const endIdx = readme.indexOf(endMark);

if (startIdx < 0 || endIdx < 0) {
  // First-time injection: append at the end.
  writeFileSync(README, readme.replace(/\n+$/, '') + '\n\n' + block + '\n');
} else {
  const before = readme.slice(0, startIdx);
  const after = readme.slice(endIdx + endMark.length);
  writeFileSync(README, before + block + after);
}

console.log(`Wrote coverage map (${listFolders().length} folders).`);
